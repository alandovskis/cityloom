class OnlyVersion(unittest.TestCase):
    def test_the_root_version_alone_is_only_a_version(self):
        self.assertTrue(only_version("Cargo.toml", TOML, bumped(TOML, '"0.21.0"', '"0.21.1"')))
        self.assertTrue(only_version("Cargo.lock", LOCK, bumped(LOCK, 'version = "0.21.0"', 'version = "0.21.1"')))

    def test_a_dependency_or_another_crate_is_more(self):
        dependency = bumped(TOML, 'serde = { version = "1"', 'serde = { version = "2"')
        self.assertFalse(only_version("Cargo.toml", TOML, dependency))
        self.assertFalse(only_version("Cargo.toml", TOML, bumped(TOML, 'version = "0.1.0"', 'version = "0.2.0"')))
        self.assertFalse(only_version("Cargo.lock", LOCK, bumped(LOCK, '"1.0.228"', '"1.0.229"')))

    def test_the_version_and_a_dependency_together_are_more(self):
        toml = bumped(bumped(TOML, '"0.21.0"', '"0.21.1"'), 'version = "1"', 'version = "2"')
        self.assertFalse(only_version("Cargo.toml", TOML, toml))

    def test_a_file_added_removed_or_of_another_name_is_more(self):
        self.assertFalse(only_version("Cargo.toml", None, TOML))
        self.assertFalse(only_version("Cargo.toml", TOML, None))
        self.assertFalse(only_version("src/lib.rs", "a", "a"))


class Targets(unittest.TestCase):
    def test_a_version_bump_with_documents_deploys_nothing(self):
        texts = {
            ("old", "Cargo.toml"): TOML,
            ("new", "Cargo.toml"): bumped(TOML, '"0.21.0"', '"0.21.1"'),
            ("old", "Cargo.lock"): LOCK,
            ("new", "Cargo.lock"): bumped(LOCK, 'version = "0.21.0"', 'version = "0.21.1"'),
        }
        paths = ["CLAUDE.md", "Cargo.toml", "Cargo.lock", "e2e/tests/map.spec.ts"]
        got = targets(paths, lambda side, p: texts[side, p])
        self.assertEqual(got, {"site": [], "docs": []})

    def test_code_deploys_the_site_and_the_documentation_its_own(self):
        no_text = lambda side, p: None
        self.assertEqual(targets(["src/lib.rs", "CLAUDE.md"], no_text), {"site": ["src/lib.rs"], "docs": []})
        self.assertEqual(targets(["website/docs/intro.md"], no_text), {"site": [], "docs": ["website/docs/intro.md"]})
        ci = ".github/workflows/ci.yml"
        self.assertEqual(targets([ci], no_text), {"site": [ci], "docs": [ci]})
        self.assertEqual(targets([], no_text), {"site": [], "docs": []})


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout.strip()


class FromGit(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.repo = Path(self.dir.name)
        git(self.repo, "init", "-q", "-b", "main")
        git(self.repo, "config", "user.email", "t@example.com")
        git(self.repo, "config", "user.name", "t")
        self.write("Cargo.toml", TOML)
        self.write("Cargo.lock", LOCK)
        self.write("src/lib.rs", "fn a() {}\n")
        self.first = self.commit()

    def write(self, path: str, text: str):
        (self.repo / path).parent.mkdir(parents=True, exist_ok=True)
        (self.repo / path).write_text(text)

    def commit(self) -> str:
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-q", "-m", "x")
        return git(self.repo, "rev-parse", "HEAD")

    def run_main(self, before: str, after: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = what_to_deploy.main([before, after, "--repo", str(self.repo)])
        return code, out.getvalue(), err.getvalue()

    def test_a_version_bump_and_a_document_deploy_nothing_and_say_why(self):
        self.write("Cargo.toml", bumped(TOML, '"0.21.0"', '"0.21.1"'))
        self.write("Cargo.lock", bumped(LOCK, 'version = "0.21.0"', 'version = "0.21.1"'))
        self.write("CLAUDE.md", "notes\n")
        code, out, err = self.run_main(self.first, self.commit())
        self.assertEqual((code, out), (0, "site=false\ndocs=false\n"))
        self.assertIn("nothing to deploy", err)

    def test_code_changed_over_several_commits_deploys_and_names_it(self):
        self.write("CLAUDE.md", "notes\n")
        self.commit()
        self.write("src/lib.rs", "fn b() {}\n")
        code, out, err = self.run_main(self.first, self.commit())
        self.assertEqual((code, out), (0, "site=true\ndocs=false\n"))
        self.assertIn("src/lib.rs", err)

    def test_a_version_bump_beside_code_is_not_named_as_a_reason(self):
        self.write("Cargo.toml", bumped(TOML, '"0.21.0"', '"0.21.1"'))
        self.write("src/lib.rs", "fn b() {}\n")
        _, out, err = self.run_main(self.first, self.commit())
        self.assertEqual(out, "site=true\ndocs=false\n")
        self.assertIn("deploys (src/lib.rs)", err)
        self.assertNotIn("Cargo.toml", err)

    def test_a_file_moved_out_of_the_code_deploys(self):
        (self.repo / "docs").mkdir()
        git(self.repo, "mv", "src/lib.rs", "docs/lib.rs")
        _, out, _ = self.run_main(self.first, self.commit())
        self.assertEqual(out, "site=true\ndocs=false\n")

    def test_an_unknown_or_empty_before_deploys_everything(self):
        after = git(self.repo, "rev-parse", "HEAD")
        for before in ["0" * 40, "", "1234567890abcdef1234567890abcdef12345678"]:
            with self.subTest(before):
                code, out, err = self.run_main(before, after)
                self.assertEqual((code, out), (0, "site=true\ndocs=true\n"))
                self.assertIn("deploying everything", err)


